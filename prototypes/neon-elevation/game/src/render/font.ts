export const CHAR_W = 6; // 5px glyph + 1px advance
export const CHAR_H = 7;

export function textWidth(str: string): number {
  return str.length * CHAR_W - 1;
}

export function drawText(
  g: CanvasRenderingContext2D,
  str: string,
  x: number,
  y: number,
  color: string,
  alpha = 1,
): void {
  g.globalAlpha = alpha;
  g.fillStyle = color;
  let cx = x;
  for (const ch of str.toUpperCase()) {
    const glyph = GLYPHS[ch];
    if (glyph) {
      const rows = glyph.split('|');
      for (let r = 0; r < CHAR_H; r++) {
        const row = rows[r];
        for (let c = 0; c < 5; c++) if (row[c] === '#') g.fillRect(cx + c, y + r, 1, 1);
      }
    }
    cx += CHAR_W;
  }
  g.globalAlpha = 1;
}
